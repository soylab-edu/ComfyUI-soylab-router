export function routerText(app, key, values = {}) {
  const locale = routerLocale(app);
  const template = messages[locale][key] ?? messages.ko[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

