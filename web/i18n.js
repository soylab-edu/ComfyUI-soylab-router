// ComfyUI's Comfy.Locale setting is the source of truth. Unknown locales use Korean.
export function routerLocale(app) {
  const configured = app?.ui?.settings?.getSettingValue?.("Comfy.Locale");
  const language = String(configured || "ko").toLowerCase();
  if (language.startsWith("en")) return "en";
  if (language.startsWith("ja")) return "ja";
  if (language.startsWith("zh")) return "zh";
  return "ko";
}

